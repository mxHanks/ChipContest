#!/usr/bin/env python3
"""Local structure, mock VPI and classifier checks; no mapped/native qualification."""
import argparse
import ast
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import unknown167 as u

HERE=Path(__file__).resolve().parent
REPO=HERE.parent.parent


def need(ok,message):
    if not ok:
        raise AssertionError(message)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--out',type=Path,required=True)
    p.add_argument('--adapter147',type=Path,default=REPO/'build/xu-campaign-batch154/private147')
    p.add_argument('--capture',type=Path,default=REPO/'build/xu-score-resume-20261103/next-results-export-53/s2c-formal-activity12-20261103-23')
    p.add_argument('--macro-inventory',type=Path,default=REPO/'build/xu-score-resume-20261103/terminal-results-export-22/s2c-pt-macro-pin-inventory-20261103-20/inventory.json')
    p.add_argument('--original147-evidence',type=Path,default=REPO/'build/xu-score-resume-20261103/serverfailed159/s2c-private-native-20261105-147')
    p.add_argument('--vpi-include',type=Path,default=Path('/usr/include/iverilog'))
    args=p.parse_args();out=args.out.resolve();out.mkdir(parents=True,exist_ok=False);checks=[]

    def command(name,argv):
        argv=[str(x) for x in argv];log=out/(name+'.log')
        with log.open('xb') as f:
            result=subprocess.run(argv,stdout=f,stderr=subprocess.STDOUT,timeout=60)
        need(result.returncode==0,name+': '+log.read_text())
        checks.append(dict(name=name,argv=argv,returncode=result.returncode,log_sha256=u.sha(log)))
        return log.read_text()

    for path in [HERE/'unknown167.py',HERE/'host_checks167.py']:
        ast.parse(path.read_text(),filename=str(path),feature_version=6)
    command('prepare',[sys.executable,'-B',HERE/'unknown167.py','--adapter147',args.adapter147.resolve(),
        '--capture',args.capture.resolve(),'--macro-inventory',args.macro_inventory.resolve(),'--out',out/'prepared'])
    prepared=out/'prepared';state=json.loads((prepared/'state.json').read_text())
    need(state['status']==u.PREPARED and state['inputs_equal_before_after'] and not state['identity_errors'],'prepare identity/status differs')
    m=u.load147(args.adapter147);original=(args.capture/'simulator/tb_xu_s2c_task_activity.sv').read_text()
    records=m.create_plan(original);old_tb,old_review=m.generated_tb(original,records)
    need(old_tb==(args.original147_evidence/'tb_private147.sv').read_text(),'original generated147 TB differs from actual159 bytes')
    tb=u.tb_instrument(old_tb);c=u.c_instrument(m.generate_c())
    need(tb==(prepared/'tb_private147.sv').read_text() and c==(prepared/'xu_private147.c').read_text(),'prepared generated bytes differ')
    old_fatals=re.findall(r'\$fatal\(1,"([^"\n]*)"',old_tb)
    need(re.findall(r'\$fatal\(1,"([^"\n]*)"',tb)==old_fatals and len(old_fatals)==87,'all87 original147 fatals/order not preserved')
    need(re.findall(r'always\s*@\([^\n]+',tb)==re.findall(r'always\s*@\([^\n]+',old_tb) and
         tb.count('$xu_private147_sample(')==3,'original3 sampling edges/phase calls differ')
    observer=(HERE/'observer167.c.in').read_text()
    need(not re.search(r'\bvpi_put_value\s*\(|\bvpi_control\s*\(|vpiForceFlag|cbReadWriteSynch|cbAfterDelay',observer),'observer has DUT writes/control/scheduled phase changes')
    command('vpi-syntax',['gcc','-std=gnu99','-fsyntax-only','-Wall','-Wextra','-Werror','-isystem',args.vpi_include,
        '-I'+str(prepared),prepared/'xu_private147.c'])
    command('mock-build',['gcc','-std=gnu99','-Wall','-Wextra','-Werror','-isystem',args.vpi_include,'-I'+str(HERE),
        '-x','c',HERE/'mock167.c.in','-o',out/'mock167'])
    mock=command('mock-00',[out/'mock167','0'])
    need('MOCK167_PASS nodes=36 callbacks=36 four_state=1 forbidden_VPI_write_symbols=0 native_VCS_proof=0' in mock,'mock mechanism checks missing')
    for mode in range(1,7):
        data=command('mock-%02d'%mode,[out/'mock167',str(mode)])
        need('MOCK167_PASS' not in data,'invalid synthetic native geometry accepted')
    command('full-tb-syntax',['iverilog','-g2012','-DXU_TASK_ACTIVITY_HOST_CHECK','-s','tb_xu_soc_ppa','-tnull',
        prepared/'tb_private147.sv',REPO/'build/xu-mapped-private147/local-checks-v1/structural-stub.sv'])
    # A synthetic merged log tests strict parsing only, using real147 binding
    # provenance and mock167 observations. It is never a server result.
    actual=(args.original147_evidence/'simulation.log').read_text()
    need(hashlib.sha256(actual.encode()).hexdigest()=='3a231022be64a2a8a2e341f9f1c86023c16bd53d9c029d2c60b5c0b41f86c6b3','actual159 original147 log differs')
    prefix=actual[:actual.index('Fatal:')]
    observed=mock[:mock.index('MOCK167_PASS')]
    split=next(line for line in observed.splitlines() if 'reason=before_original_unknown_fatal' in line)
    before,after=observed.split(split,1)
    trigger='XU_UNKNOWN167_TRIGGER tick_fs=9359423333333 '+' '.join(name+'='+'0'*(width-1)+'x' for name,_,width in u.EIGHT)+'\n'
    fatal_line=next(i for i,line in enumerate(tb.splitlines(),1) if '$fatal(1,"'+u.FATAL+'")' in line)
    path=str(prepared/'tb_private147.sv')
    fatal='Fatal: "%s", %d: tb_xu_soc_ppa.xu_observe_candidate: at time 9359423333333 fs\n%s\n$finish called from file "%s", line %d.\n$finish at simulation time 9359423333333\n'%(path,fatal_line,u.FATAL,path,fatal_line)
    raw=(prefix+before+trigger+split+after+fatal).encode()
    bindings=json.loads((prepared/'adapter-plan147.json').read_text())['bindings']
    result=u.classify_unknown(raw,0,prepared/'tb_private147.sv',bindings)
    need(result['status']==u.COLLECTED and result['unknown_operands']==[r[0] for r in u.EIGHT] and
         result['passive_snapshot_nodes']==36 and not result['current_native_vs_sampled_differences'],'valid synthetic log classification differs')
    # VCS147 actually returns0 on this native fatal; code is evidence, never a
    # substitute for exact native source/message/time block and retained checks.
    need(u.classify_unknown(raw,1,prepared/'tb_private147.sv',bindings)['native_simulation_returncode']==1,'native returncode not preserved')
    changed=re.sub(rb'(reason=before_original_unknown_fatal role=w_commit bits=1 aval=)0000000000000001 bval=0000000000000001',
                   rb'\g<1>0000000000000000 bval=0000000000000000',raw,count=1)
    need(u.classify_unknown(changed,0,prepared/'tb_private147.sv',bindings)['current_native_vs_sampled_differences']==['w_commit'],
         'native versus sampled difference was collapsed')
    z_raw=raw.replace(b'w_commit=x ',b'w_commit=z ',1)
    z_raw=re.sub(rb'(reason=before_original_unknown_fatal role=(?:w_commit|tb_fatal_operand) bits=1 aval=)0000000000000001( bval=0000000000000001 name=(?:'+
                 re.escape((u.ACCEL+'.io_wLoadWen').encode())+b'|tb_xu_soc_ppa.xu147_o_048)\n)',rb'\g<1>0000000000000000\g<2>',z_raw)
    need(u.classify_unknown(z_raw,0,prepared/'tb_private147.sv',bindings)['original_unknown_values']['w_commit']=='z','native high impedance was collapsed')
    (out/'synthetic-parser-fixture.log').write_bytes(raw)
    negatives=[
        ('missing-trigger',raw.replace(trigger.encode(),b'')),
        ('missing-original-fatal',raw.replace(fatal.encode(),b'')),
        ('duplicate-fatal',raw+fatal.encode()),
        ('wrong-native-time',raw.replace(b'at time 9359423333333 fs',b'at time 9359423333334 fs')),
        ('wrong-finish-time',raw.replace(b'$finish at simulation time 9359423333333',b'$finish at simulation time 1')),
        ('wrong-source',raw.replace(path.encode(),b'/wrong/tb.sv')),
        ('wrong-trigger-width',raw.replace(b'row_count=0x',b'row_count=x')),
        ('wrong-trigger-value',raw.replace(b'w_commit=x ',b'w_commit=z ',1)),
        ('wrong-ready',raw.replace(b'observed_nodes=36 failed=0',b'observed_nodes=36 failed=1')),
        ('wrong-ready-count',raw.replace(b'observed_nodes=36 failed=0',b'observed_nodes=35 failed=0')),
        ('missing-CK-binding',raw.replace(b'role=fifo_CK bits=1 type=36',b'role=wrong_CK bits=1 type=36',1)),
        ('missing-native-binding',raw.replace(b'XU_PRIVATE147_BIND tag=83',b'XU_PRIVATE147_BAD tag=83',1)),
        ('bad-serial',raw.replace(b'EVENT serial=1 ',b'EVENT serial=2 ',1)),
        ('late-snapshot',raw.replace(b'SNAPSHOT_DONE nodes=36 failed=0 tick_fs=9359423333333',b'SNAPSHOT_DONE nodes=36 failed=0 tick_fs=1')),
        ('SOC_PASS',raw+b'SOC_PASS tasks=1\n'),
        ('original-adapter-error',raw+b'XU_PRIVATE147_ADAPTER_REJECT\n'),
        ('unexpected-native-error',raw+b'Error: unexpected\n')]
    for name,data in negatives:
        try:u.classify_unknown(data,0,prepared/'tb_private147.sv',bindings)
        except ValueError:pass
        else:raise AssertionError('malformed fixture accepted: '+name)
    report=dict(schema='xu-unknown167-local-review-v1',status='LOCAL_STRUCTURE_MOCK_PARSER_PASS_NOT_NATIVE_VCS_OR_QUALIFICATION',
        qualification='NOT_QUALIFIED',checks=checks,classifier_negative_cases=len(negatives),mock_modes=7,
        original147_files=u.FROZEN147,original_fatal_count=87,original_always_blocks=3,original_sampler_calls=3,
        original147_tb_sha256=hashlib.sha256(old_tb.encode()).hexdigest(),generated167_tb_sha256=u.sha(prepared/'tb_private147.sv'),
        generated167_c_sha256=u.sha(prepared/'xu_private147.c'),original_actual159_log_sha256=hashlib.sha256(actual.encode()).hexdigest(),
        new_vpi_writes=0,forbidden_controls=0,limitations=['No native VCS run, timing, causality, physical storage, activity or energy qualification.',
            'Icarus checks syntax only with a separate structural fixture; fake VPI objects do not prove native handle availability or scheduling.',
            'Synthetic merged parser log is explicitly local; never adopt it as native or qualification evidence.'])
    (out/'review167.json').write_text(json.dumps(report,sort_keys=True,indent=2)+'\n')
    print(report['status'])


if __name__=='__main__':
    main()
